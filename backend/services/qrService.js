/* ============================================================
   qrService.js
   NEW FILE — added for the Gatekeeper QR Movement workflow.

   Responsible for:
     - Turning an approved Leave/Outpass request into a signed,
       compact QR payload that contains NO student personal data
       (only request_type + request_id + the existing token_no).
     - Verifying that payload again when the Gatekeeper scans it.
     - Rendering the payload as a QR code image (data URL) for
       embedding in the approval email.

   Does not touch students.csv / leave_requests.csv / outpass_requests.csv.
   Uses the request's EXISTING token_no (already generated by
   outpassController/leaveController) as the secret-bearing part —
   no new "QR token" column was added to those CSVs.
   ============================================================ */

const crypto = require("crypto");
const QRCode = require("qrcode");

// Falls back to a fixed dev secret if QR_SECRET is not set in .env,
// but logs a warning so it's not silently insecure in production.
const QR_SECRET = process.env.QR_SECRET || "hostelerp-dev-qr-secret-change-me";
if (!process.env.QR_SECRET) {
    console.warn("[qrService] QR_SECRET is not set in backend/.env — using an insecure default. Add QR_SECRET=<random string> to .env before production use.");
}

function base64url(input) {
    return Buffer.from(input).toString("base64")
        .replace(/\+/g, "-")
        .replace(/\//g, "_")
        .replace(/=+$/, "");
}

function base64urlDecode(input) {
    input = input.replace(/-/g, "+").replace(/_/g, "/");
    while (input.length % 4) input += "=";
    return Buffer.from(input, "base64").toString("utf8");
}

function sign(payloadStr) {
    return crypto.createHmac("sha256", QR_SECRET).update(payloadStr).digest("hex").slice(0, 32);
}

/**
 * Build the signed string that gets encoded into the QR image.
 * Contains ONLY: request type, request id, and the existing token_no.
 * No name, room, phone, or other personal data.
 *
 * NEW — this payload now carries a "t" (kind) discriminator so the
 * gatekeeper can tell an exit-authorization QR apart from a dynamic
 * single-use return QR (see buildReturnQrPayload below) when the
 * SAME scanner/input is used for both. Old QRs already emailed to
 * students before this change have no "t" field — verifyQrPayload
 * treats a missing "t" as "exit" so they keep working.
 */
function buildQrPayload({ requestType, requestId, tokenNo }) {
    const payload = JSON.stringify({
        t: "exit",
        rt: requestType,   // "outpass" | "leave"
        rid: String(requestId),
        tk: String(tokenNo)
    });
    const encoded = base64url(payload);
    const signature = sign(encoded);
    return `${encoded}.${signature}`;
}

/**
 * NEW — build the signed string for a dynamic, single-use RETURN QR.
 * Contains ONLY an opaque, cryptographically random token — no
 * request id, student id, name, or any other personal/identifying
 * data. The token itself is meaningless without the corresponding
 * server-side record in qr_tokens.csv (see qrTokenStore.js), which
 * is what actually tracks ACTIVE / USED / EXPIRED state.
 */
function buildReturnQrPayload({ token }) {
    const payload = JSON.stringify({
        t: "return",
        tok: String(token)
    });
    const encoded = base64url(payload);
    const signature = sign(encoded);
    return `${encoded}.${signature}`;
}

/**
 * NEW — generate a cryptographically random, unpredictable token to
 * back a single-use return QR. 24 random bytes (192 bits) encoded
 * base64url — not derived from any request id, roll number, or
 * other guessable/sequential value.
 */
function generateSecureToken() {
    return crypto.randomBytes(24).toString("base64url");
}

/**
 * Verify a scanned/typed QR string. Returns { valid, data, reason }.
 * data.t is normalized to "exit" when absent (back-compat with QRs
 * generated before the "t" discriminator existed).
 */
function verifyQrPayload(qrString) {
    try {
        if (!qrString || typeof qrString !== "string" || !qrString.includes(".")) {
            return { valid: false, reason: "Malformed QR code." };
        }
        const [encoded, signature] = qrString.split(".");
        const expectedSig = sign(encoded);
        if (signature !== expectedSig) {
            return { valid: false, reason: "Invalid or tampered QR code." };
        }
        const data = JSON.parse(base64urlDecode(encoded));
        data.t = data.t || "exit";

        if (data.t === "return") {
            if (!data.tok) {
                return { valid: false, reason: "Invalid QR code." };
            }
            return { valid: true, data };
        }

        if (!data.rt || !data.rid || !data.tk) {
            return { valid: false, reason: "Invalid QR code." };
        }
        return { valid: true, data };
    } catch (e) {
        return { valid: false, reason: "Invalid QR code." };
    }
}

/**
 * Generate a QR code image as a PNG data URL for embedding in email.
 */
async function generateQrDataUrl(qrString) {
    return QRCode.toDataURL(qrString, {
        errorCorrectionLevel: "M",
        margin: 2,
        width: 260
    });
}

module.exports = {
    buildQrPayload,
    buildReturnQrPayload,
    generateSecureToken,
    verifyQrPayload,
    generateQrDataUrl
};
